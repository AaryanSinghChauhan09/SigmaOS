#!/usr/bin/env python3
"""Generate one GitHub Wiki page per registered SigmaOS component.

COMPONENTS.toml remains the source of truth. When duplicate declarations have
conflicting metadata, the generated page shows each distinct value rather than
silently selecting one and hiding the registry inconsistency.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
import tomllib
from collections import defaultdict
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
REGISTRY = ROOT / "COMPONENTS.toml"
FIELDS = ("description", "repo", "engine", "category", "language", "visibility")


def slug(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9-]+", "-", name).strip("-")


def inline(value: object) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ")


def unique_values(records: list[dict], key: str) -> list[object]:
    values: list[object] = []
    for record in records:
        value = record.get(key, "unspecified")
        if value not in values:
            values.append(value)
    return values


def render_component(name: str, records: list[dict], page_slugs: dict[str, str]) -> str:
    lines = [
        f"# {name}",
        "",
        "This page is generated from the SigmaOS umbrella repository's `COMPONENTS.toml`.",
        "The linked component repository owns implementation details; this page records its registered boundary and integration metadata.",
        "",
    ]

    repos = unique_values(records, "repo")
    lines += ["## Repository", ""]
    lines += [f"- [{repo}]({repo})" for repo in repos]
    if len(records) > 1:
        lines += ["", f"> The registry contains {len(records)} declarations for this name. Distinct metadata values are listed below so conflicts remain visible."]

    lines += ["", "## Registered metadata", "", "| Field | Registry value(s) |", "| --- | --- |"]
    for field in FIELDS:
        values = unique_values(records, field)
        rendered = "<br>".join(inline(value) for value in values)
        lines.append(f"| `{field}` | {rendered} |")

    dependencies = list(dict.fromkeys(dep for record in records for dep in record.get("depends_on", [])))
    lines += ["", "## Dependencies", ""]
    if dependencies:
        for dependency in dependencies:
            if dependency in page_slugs:
                lines.append(f"- [{dependency}](Component-{page_slugs[dependency]}.md)")
            else:
                lines.append(f"- `{inline(dependency)}` (not present in the current component registry)")
    else:
        lines.append("- None declared.")

    inspirations = list(dict.fromkeys(
        item
        for record in records
        for item in (record.get("inspirations", []) if isinstance(record.get("inspirations", []), list) else [record.get("inspirations")])
        if item not in (None, "", "None")
    ))
    lines += ["", "## Inspirations", ""]
    lines += [f"- [{item}]({item})" if str(item).startswith(("https://", "http://")) else f"- {inline(item)}" for item in inspirations]
    if not inspirations:
        lines.append("- None declared.")

    lines += [
        "",
        "## Change and integration guidance",
        "",
        "- Keep the component API narrow and document externally observable behavior in the component repository.",
        "- Keep policy in the owning component and mechanism in lower-level dependencies; use declared dependencies as the integration boundary.",
        "- Update `COMPONENTS.toml` and this generated wiki page together when the repository URL, ownership, or dependency contract changes.",
        "- Do not infer implementation maturity or test status from registry metadata; use the linked repository's CI and release evidence.",
        "",
        "---",
        "Generated by `scripts/generate_component_wiki.py`.",
        "",
    ]
    return "\n".join(lines)


def render_index(
    groups: dict[str, list[str]], page_slugs: dict[str, str], entries: list[dict]
) -> str:
    count = sum(map(len, groups.values()))
    duplicate_names = sum(len(names) > 1 for names in groups.values())
    repo_count = len({str(entry.get("repo", "")) for entry in entries if entry.get("repo")})
    lines = [
        "# SigmaOS component index",
        "",
        "This index and the linked pages are generated from `COMPONENTS.toml` in the SigmaOS umbrella repository.",
        "Each registered component has a dedicated wiki page. Component implementation and releases remain owned by its linked repository.",
        "",
        f"Registry snapshot: **{len(entries)} declarations**, **{count} distinct component names**, **{duplicate_names} names with repeated declarations**, and **{repo_count} distinct repository URLs**.",
        "",
    ]
    for category in sorted(groups, key=str.casefold):
        lines += [f"## {category}", ""]
        for name in sorted(groups[category], key=str.casefold):
            lines.append(f"- [{name}](Component-{page_slugs[name]}.md)")
        lines.append("")
    lines += ["---", "Generated by `scripts/generate_component_wiki.py`.", ""]
    return "\n".join(lines)


def generated_content() -> dict[str, str]:
    entries = tomllib.loads(REGISTRY.read_text(encoding="utf-8"))["component"]
    grouped: dict[str, list[dict]] = defaultdict(list)
    for entry in entries:
        grouped[entry["name"]].append(entry)
    names = set(grouped)
    initial_slugs = {name: slug(name) for name in names}
    counts: dict[str, int] = defaultdict(int)
    for value in initial_slugs.values():
        counts[value.casefold()] += 1
    page_slugs = {
        name: (
            f"{value}-{hashlib.sha256(name.encode('utf-8')).hexdigest()[:8]}"
            if counts[value.casefold()] > 1
            else value
        )
        for name, value in initial_slugs.items()
    }
    files: dict[str, str] = {}
    categories: dict[str, list[str]] = defaultdict(list)
    for name, records in grouped.items():
        filename = f"Component-{page_slugs[name]}.md"
        if filename in files:
            raise ValueError(f"wiki filename collision for {name!r}: {filename}")
        files[filename] = render_component(name, records, page_slugs)
        category_values = unique_values(records, "category")
        category = str(category_values[0]) if len(category_values) == 1 else "Registry metadata conflicts"
        categories[category].append(name)
    files["Components.md"] = render_index(categories, page_slugs, entries)
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--wiki-dir", type=Path, required=True, help="checked-out GitHub Wiki repository")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="write generated component pages")
    mode.add_argument("--check", action="store_true", help="fail if generated pages are missing or stale")
    args = parser.parse_args()
    if not args.wiki_dir.is_dir():
        parser.error(f"wiki directory does not exist: {args.wiki_dir}")

    try:
        expected = generated_content()
    except (KeyError, TypeError, ValueError) as exc:
        print(f"component wiki generation failed: {exc}", file=sys.stderr)
        return 2

    stale: list[str] = []
    for filename, content in expected.items():
        path = args.wiki_dir / filename
        if args.write:
            path.write_text(content, encoding="utf-8")
        elif not path.is_file() or path.read_text(encoding="utf-8") != content:
            stale.append(filename)

    if stale:
        print(f"{len(stale)} generated wiki page(s) are missing or stale:")
        print("\n".join(stale[:100]))
        if len(stale) > 100:
            print(f"... and {len(stale) - 100} more")
        return 1

    print(f"{'wrote' if args.write else 'validated'} {len(expected) - 1} component pages and Components.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
