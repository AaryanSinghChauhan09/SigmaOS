#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_debian_apt_mirror_ranker() {
        let mut ranker = DebianAptFastMirrorRanker::new();
        ranker.register_mirror(AptMirrorServer {
            mirror_url: "http://slow.debian.org/debian".to_string(),
            country: "US".to_string(),
            latency_ms: 150,
            throughput_kbps: 5000,
        });
        ranker.register_mirror(AptMirrorServer {
            mirror_url: "http://fast.debian.org/debian".to_string(),
            country: "DE".to_string(),
            latency_ms: 20,
            throughput_kbps: 50000,
        });

        let sources = ranker.generate_sources_list("bookworm", 1);
        assert!(sources.contains("fast.debian.org"));
    }

    #[test]
    fn test_arch_pacman_delta_sync() {
        let mut sync = ArchPacmanDeltaSyncEngine::new();
        sync.register_patch(PacmanDeltaPatch {
            package_name: "bash".to_string(),
            old_version: "5.1".to_string(),
            new_version: "5.2".to_string(),
            patch_bytes: b"-DELTA-V2".to_vec(),
            patch_sha256: "sha256-delta".to_string(),
        });

        let reconstructed = sync.apply_patch("bash", "5.1", "5.2", b"OLD_PAYLOAD").unwrap();
        assert_eq!(reconstructed, b"OLD_PAYLOAD-DELTA-V2");
    }

    #[test]
    fn test_fedora_dnf_group_solver() {
        let mut solver = FedoraDnfGroupInstallSolver::new();
        solver.register_group(DnfGroupPackageSpec {
            group_id: "development-tools".to_string(),
            group_name: "Development Tools".to_string(),
            mandatory_packages: vec!["gcc".to_string(), "make".to_string()],
            default_packages: vec!["gdb".to_string()],
            optional_packages: vec!["valgrind".to_string()],
        });

        let pkgs = solver.resolve_group_packages("development-tools", true, false).unwrap();
        assert_eq!(pkgs, vec!["gcc", "make", "gdb"]);
    }

    #[test]
    fn test_freebsd_pkg_base_engine() {
        let mut base_engine = FreeBsdPkgBaseRootfsEngine::new("default");
        base_engine.register_base_package(BasePackageRecord {
            package_name: "FreeBSD-kernel-GENERIC".to_string(),
            version: "14.0-RELEASE".to_string(),
            is_kernel: true,
            target_rootfs: "/".to_string(),
        });

        assert!(base_engine.verify_base_integrity());
        let new_be = base_engine.create_boot_environment_snapshot("14.1-RELEASE");
        assert_eq!(new_be, "/zfs/ROOT/14.1-RELEASE");
    }
}
