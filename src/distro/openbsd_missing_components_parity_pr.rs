#[derive(Debug, Clone)]
pub struct OpenBsdKarlPinsyscallPrEngine {
    pub kernel_boot_seed: u64,
    pub relinked_kernel_hash: String,
    pub pinned_syscall_ranges: BTreeMap<u32, (u64, u64)>, // syscall_num -> (start_addr, end_addr)
}

impl OpenBsdKarlPinsyscallPrEngine {
    pub fn new() -> Self {
        let mut ranges = BTreeMap::new();
        // syscall 0 (sys_exit), syscall 3 (sys_read), syscall 4 (sys_write)
        ranges.insert(0, (0xFFFFFFFF81001000, 0xFFFFFFFF81001050));
        ranges.insert(3, (0xFFFFFFFF81002000, 0xFFFFFFFF81002100));
        ranges.insert(4, (0xFFFFFFFF81002200, 0xFFFFFFFF81002300));
        Self {
            kernel_boot_seed: 0xDED1_C47A_8899_0011,
            relinked_kernel_hash: "sha256:7f8a9b0c1d2e3f4a5b6c7d8e9f0a1b2c".to_string(),
            pinned_syscall_ranges: ranges,
        }
    }

    pub fn verify_pinsyscall(&self, syscall_num: u32, callsite_addr: u64) -> bool {
        if let Some(&(start, end)) = self.pinned_syscall_ranges.get(&syscall_num) {
            callsite_addr >= start && callsite_addr <= end
        } else {
            false
        }
    }

    pub fn generate_karl_relink_diff(&mut self, new_seed: u64) -> String {
        self.kernel_boot_seed = new_seed;
        self.relinked_kernel_hash = format!(
            "sha256:{:016x}{:016x}",
            new_seed,
            new_seed ^ 0xA5A5_5A5A_A5A5_5A5A
        );
        format!(
            "--- a/usr/libexec/relink\n+++ b/usr/libexec/relink\n@@ -1,1 +1,1 @@\n-KARL_SEED=0x0000\n+KARL_SEED=0x{:016x}\n",
            new_seed
        )
    }
}

impl Default for OpenBsdKarlPinsyscallPrEngine {
    fn default() -> Self {
        Self::new()
    }
}

