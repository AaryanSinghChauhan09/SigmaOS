// 4. Signify Ed25519 Release Verification PR Engine
// ============================================================================

#[derive(Debug, Clone)]
pub struct OpenBsdSignifyKey {
    pub key_name: String,
    pub public_key: String,
    pub is_trusted: bool,
}

#[derive(Debug, Clone)]
pub struct OpenBsdSignifyEd25519PrEngine {
    pub trusted_keys: BTreeMap<String, OpenBsdSignifyKey>,
}

impl OpenBsdSignifyEd25519PrEngine {
    pub fn new() -> Self {
        let mut keys = BTreeMap::new();
        keys.insert(
            "openbsd-76-base".to_string(),
            OpenBsdSignifyKey {
                key_name: "openbsd-76-base".to_string(),
                public_key: "untrusted comment: openbsd 7.6 public key\nRWSQ0/f5vL/1n1321XG3/g5A0319203912093810293".to_string(),
                is_trusted: true,
            },
        );
        Self { trusted_keys: keys }
    }

    pub fn verify_signature(&self, key_name: &str, _file_content: &[u8], sig_header: &str) -> bool {
        if let Some(key) = self.trusted_keys.get(key_name) {
            key.is_trusted && sig_header.contains("untrusted comment: verify with")
        } else {
            false
        }
    }

    pub fn add_trusted_key(&mut self, key_name: &str, pubkey: &str) -> String {
        self.trusted_keys.insert(
            key_name.to_string(),
            OpenBsdSignifyKey {
                key_name: key_name.to_string(),
                public_key: pubkey.to_string(),
                is_trusted: true,
            },
        );
        format!(
            "--- a/etc/signify/{}.pub\n+++ b/etc/signify/{}.pub\n@@ -0,0 +1,2 @@\n+{}\n",
            key_name, key_name, pubkey
        )
    }
}

impl Default for OpenBsdSignifyEd25519PrEngine {
    fn default() -> Self {
        Self::new()
    }
}

