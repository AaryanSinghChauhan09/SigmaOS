// ============================================================================
// 1. CARP / pfsync High Availability Firewall PR Engine
// ============================================================================

#[derive(Debug, Clone)]
pub struct OpenBsdCarpInterface {
    pub vhid: u8,
    pub interface: String,
    pub advbase: u8,
    pub advskew: u8,
    pub state: String, // "MASTER" or "BACKUP"
    pub carpdev: String,
    pub pass: String,
}

#[derive(Debug, Clone)]
pub struct OpenBsdPfsyncState {
    pub syncdev: String,
    pub syncpeer: Option<String>,
    pub synchronized_states_count: u32,
}

#[derive(Debug, Clone)]
pub struct OpenBsdPfsyncCarpPrEngine {
    pub carp_interfaces: BTreeMap<u8, OpenBsdCarpInterface>,
    pub pfsync: OpenBsdPfsyncState,
}

impl OpenBsdPfsyncCarpPrEngine {
    pub fn new() -> Self {
        let mut carp = BTreeMap::new();
        carp.insert(
            1,
            OpenBsdCarpInterface {
                vhid: 1,
                interface: "carp0".to_string(),
                advbase: 1,
                advskew: 0,
                state: "MASTER".to_string(),
                carpdev: "em0".to_string(),
                pass: "secretpass".to_string(),
            },
        );
        Self {
            carp_interfaces: carp,
            pfsync: OpenBsdPfsyncState {
                syncdev: "em1".to_string(),
                syncpeer: Some("224.0.0.240".to_string()),
                synchronized_states_count: 128,
            },
        }
    }

    pub fn configure_carp_vhid(&mut self, vhid: u8, carpdev: &str, advskew: u8) -> String {
        let carp = OpenBsdCarpInterface {
            vhid,
            interface: format!("carp{}", vhid),
            advbase: 1,
            advskew,
            state: if advskew == 0 {
                "MASTER".to_string()
            } else {
                "BACKUP".to_string()
            },
            carpdev: carpdev.to_string(),
            pass: "autogenerated_pass".to_string(),
        };
        self.carp_interfaces.insert(vhid, carp);
        format!(
            "--- a/etc/hostname.carp{}\n+++ b/etc/hostname.carp{}\n@@ -0,0 +1,1 @@\n+inet 192.168.1.1 255.255.255.0 192.168.1.255 vhid {} carpdev {} advskew {}\n",
            vhid, vhid, vhid, carpdev, advskew
        )
    }

    pub fn sync_pfsync_states(&mut self, additional_states: u32) -> u32 {
        self.pfsync.synchronized_states_count += additional_states;
        self.pfsync.synchronized_states_count
    }
}

impl Default for OpenBsdPfsyncCarpPrEngine {
    fn default() -> Self {
        Self::new()
    }
}

// ============================================================================
// 2. OpenBSD Pledge & Unveil Security Sandbox PR Engine
// ============================================================================

#[derive(Debug, Clone)]
pub struct OpenBsdUnveilRule {
    pub path: String,
    pub permissions: String, // e.g. "r", "rw", "rx", "c"
}

#[derive(Debug, Clone)]
pub struct OpenBsdPledgeUnveilMatrixPrEngine {
    pub promises: Vec<String>,
    pub execpromises: Option<Vec<String>>,
    pub unveil_rules: BTreeMap<String, OpenBsdUnveilRule>,
    pub is_locked: bool,
}

impl OpenBsdPledgeUnveilMatrixPrEngine {
    pub fn new() -> Self {
        let mut unveil = BTreeMap::new();
        unveil.insert(
            "/etc/ssl".to_string(),
            OpenBsdUnveilRule {
                path: "/etc/ssl".to_string(),
                permissions: "r".to_string(),
            },
        );
        Self {
            promises: vec![
                "stdio".to_string(),
                "rpath".to_string(),
                "wpath".to_string(),
                "cpath".to_string(),
                "inet".to_string(),
            ],
            execpromises: None,
            unveil_rules: unveil,
            is_locked: false,
        }
    }

    pub fn pledge(&mut self, promises_str: &str) -> Result<String, String> {
        if self.is_locked {
            return Err("pledge() restriction is permanently locked".to_string());
        }
        let new_promises: Vec<String> = promises_str
            .split_whitespace()
            .map(|s| s.to_string())
            .collect();
        self.promises = new_promises;
        Ok(format!(
            "--- a/src/main.c\n+++ b/src/main.c\n@@ -10,3 +10,3 @@\n-pledge(\"stdio rpath wpath cpath inet\", NULL);\n+pledge(\"{}\", NULL);\n",
            promises_str
        ))
    }

    pub fn unveil(&mut self, path: &str, perms: &str) -> Result<String, String> {
        if path.is_empty() && perms.is_empty() {
            self.is_locked = true;
            return Ok("unveil() locked path restrictions".to_string());
        }
        self.unveil_rules.insert(
            path.to_string(),
            OpenBsdUnveilRule {
                path: path.to_string(),
                permissions: perms.to_string(),
            },
        );
        Ok(format!(
            "--- a/src/main.c\n+++ b/src/main.c\n@@ -12,0 +13,1 @@\n+unveil(\"{}\", \"{}\");\n",
            path, perms
        ))
    }

    pub fn is_path_allowed(&self, path: &str, req_perm: &str) -> bool {
        if let Some(rule) = self.unveil_rules.get(path) {
            rule.permissions.contains(req_perm)
        } else {
            !self.is_locked
        }
    }
}

impl Default for OpenBsdPledgeUnveilMatrixPrEngine {
    fn default() -> Self {
        Self::new()
    }
}

