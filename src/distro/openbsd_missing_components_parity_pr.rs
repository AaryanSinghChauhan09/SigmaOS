#[derive(Debug, Clone)]
pub struct OpenBsdSignifyKey {
    pub key_name: String,
    pub public_key: String,
    pub is_trusted: bool,
}

#[derive(Debug, Clone)]
pub struct OpenBsdSignifyVerificationPrEngine {
    pub known_public_keys: BTreeMap<String, String>,
}

impl OpenBsdSignifyVerificationPrEngine {
    pub fn new() -> Self {
        let mut keys = BTreeMap::new();
        keys.insert(
            "openbsd-76-base".to_string(),
            "RWQ0/f5vL/1n1321XG3/g5A03...".to_string(),
        );
        Self {
            known_public_keys: keys,
        }
    }

    pub fn verify_signature(&self, key_id: &str, payload: &[u8]) -> bool {
        self.known_public_keys.contains_key(key_id) && !payload.is_empty()
    }
}

#[derive(Debug, Clone)]
pub struct OpenBsdBioctlSoftraidPrEngine {
    pub softraid_volumes: BTreeMap<String, String>,
}

impl OpenBsdBioctlSoftraidPrEngine {
    pub fn new() -> Self {
        let mut vols = BTreeMap::new();
        vols.insert(
            "sd1".to_string(),
            OpenBsdSoftraidVolume {
                device_node: "sd1".to_string(),
                raid_level: "CRYPTO".to_string(),
                chunk_disks: vec!["/dev/sd0a".to_string()],
                cipher: "AES-XTS-256".to_string(),
                passphrase_pbkdf2_rounds: 16000,
                is_online: true,
            },
        );
        Self {
            softraid_volumes: vols,
        }
    }

    pub fn create_crypto_volume(&mut self, target_dev: &str, chunk: &str) -> (String, String) {
        let vol = OpenBsdSoftraidVolume {
            device_node: target_dev.to_string(),
            raid_level: "CRYPTO".to_string(),
            chunk_disks: vec![chunk.to_string()],
            cipher: "AES-XTS-256".to_string(),
            passphrase_pbkdf2_rounds: 32000,
            is_online: true,
        };
        self.softraid_volumes.insert(target_dev.to_string(), vol);
        let diff = format!(
            "--- a/etc/fstab\n+++ b/etc/fstab\n@@ -0,0 +1,1 @@\n+/dev/{}a /home ffs rw,nodev,nosuid 1 2\n",
            target_dev
        );
        let cmd = format!("bioctl -c C -l {} softraid0", chunk);
        (cmd, diff)
    }
}

impl Default for OpenBsdBioctlSoftraidPrEngine {
    fn default() -> Self {
        Self::new()
    }
}

