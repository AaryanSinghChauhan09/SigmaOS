# Generate Cargo.toml
proc generateCargoToml(gen: CodeGenerator, spec: PluginSpec): string =
  result = &"""[package]
name = "{spec.name.toLowerAscii()}"
version = "0.1.0"
edition = "2021"
authors = ["SigmaOS Agent"]

[lib]
name = "{spec.name.toLowerAscii()}"
crate-type = ["cdylib", "rlib"]

[dependencies]
"""
  for dep in spec.dependencies:
    result.add(&"{dep} = \"*\"\n")

# Generate build.zig
proc generateZigBuild(gen: CodeGenerator, spec: PluginSpec): string =
  result = &"""const std = @import("std");

pub fn build(b: *std.Build) void {{
    const target = b.standardTargetOptions(.{{}});
    const optimize = b.standardOptimizeOption(.{{}});
    
    const lib = b.addStaticLibrary(.{{
        .name = "{spec.name.toLowerAscii()}",
        .root_source_file = .{{ .path = "src/{spec.name.toLowerAscii()}.zig" }},
        .target = target,
        .optimize = optimize,
    }});
    
    b.installArtifact(lib);
    
    const tests = b.addTest(.{{
        .root_source_file = .{{ .path = "src/{spec.name.toLowerAscii()}.zig" }},
        .target = target,
        .optimize = optimize,
    }});
    
    const test_step = b.step("test", "Run tests");
    test_step.dependOn(&tests.step);
}}
"""

# Generate .nimble file
proc generateNimbleFile(gen: CodeGenerator, spec: PluginSpec): string =
  result = &"""# Package

version       = "0.1.0"
