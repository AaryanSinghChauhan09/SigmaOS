# Generate plugin code from specification
proc generatePlugin*(gen: var CodeGenerator, spec: PluginSpec): GeneratedCode =
  result = GeneratedCode()
  
  case spec.language
  of Rust:
    result = gen.generateRustPlugin(spec)
  of Zig:
    result = gen.generateZigPlugin(spec)
  of Nim:
    result = gen.generateNimPlugin(spec)
  
  # Validate generated code
  let validation = gen.validate(result.sourceCode, spec.language)
  if not validation.valid:
    echo &"Warning: Generated code has validation issues"
    for error in validation.errors:
      echo &"  ERROR: {error}"
    for warning in validation.warnings:
      echo &"  WARNING: {warning}"

# Generate Rust plugin
proc generateRustPlugin(gen: CodeGenerator, spec: PluginSpec): GeneratedCode =
  let template = gen.templates[Rust]
  
  var code = template.header
    .replace("{name}", spec.name)
    .replace("{description}", spec.description)
  
  code.add(template.imports)
  code.add("\n")
  code.add(template.structDef.replace("{name}", spec.name))
  code.add("\n")
  code.add(template.methods.replace("{name}", spec.name))
  code.add("\n")
  code.add(template.tests.replace("{name}", spec.name))
  
  result.sourceCode = code
  result.buildScript = gen.generateRustBuildScript(spec)
  result.manifest = gen.generateCargoToml(spec)
  result.tests = template.tests.replace("{name}", spec.name)

