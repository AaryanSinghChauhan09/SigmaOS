description   = "{spec.description}"
license       = "MIT"

# Dependencies

requires "nim >= 1.6.0"
"""
  for dep in spec.dependencies:
    result.add(&"requires \"{dep}\"\n")

# Generate build scripts
proc generateRustBuildScript(gen: CodeGenerator, spec: PluginSpec): string =
  result = """#!/bin/bash
cargo build --release
cargo test
"""

proc generateZigBuildScript(gen: CodeGenerator, spec: PluginSpec): string =
  result = """#!/bin/bash
zig build
zig build test
"""

proc generateNimBuildScript(gen: CodeGenerator, spec: PluginSpec): string =
  result = """#!/bin/bash
nim c -d:release --noMain --app:lib src/""" & spec.name.toLowerAscii() & """.nim
nim c -r """ & spec.name.toLowerAscii() & """.nim
"""

# Validate generated code
proc validate(gen: CodeGenerator, code: string, lang: CodeLanguage): ValidationResult =
  result.valid = true
  result.errors = @[]
  result.warnings = @[]
  result.suggestions = @[]
  
  # Basic syntax checks
  if code.len == 0:
    result.valid = false
    result.errors.add("Empty code generated")
    return
  
  # Language-specific validation
  case lang
  of Rust:
    # Check for unsafe blocks
    if code.contains("unsafe"):
      result.warnings.add("Contains unsafe code blocks")
    
    # Check for unwrap() calls
    if code.contains(".unwrap()"):
      result.warnings.add("Contains unwrap() calls - consider error handling")
    
    # Check for proper error handling
    if not code.contains("Result<"):
      result.suggestions.add("Consider adding Result<T, E> error types")
  
  of Zig:
    # Check for error handling
    if not code.contains("!"):
      result.suggestions.add("Consider adding error unions")
    
    # Check for proper cleanup
    if code.contains("init") and not code.contains("deinit"):
      result.warnings.add("Init found but no corresponding deinit")
  
  of Nim:
    # Check for exception handling
    if code.contains("raise") and not code.contains("try"):
      result.warnings.add("Raises exceptions but no try blocks found")
    
    # Check for proper cleanup
    if code.contains("new") and not code.contains("cleanup"):
      result.suggestions.add("Consider adding cleanup procedures")

# Generate theme code
proc generateTheme*(gen: var CodeGenerator, name: string, colors: Table[string, string]): GeneratedCode =
  result.sourceCode = &"""# {name} Theme
# Auto-generated by SigmaOS Agent

type Theme* = object
  background*: string
  foreground*: string
  accent*: string
  border*: string

proc new{name}Theme*(): Theme =
  result = Theme(
"""
  
  for key, value in colors:
    result.sourceCode.add(&"    {key}: \"{value}\",\n")
  
  result.sourceCode.add("  )\n")

# Generate widget code
proc generateWidget*(gen: var CodeGenerator, name: string, widgetType: string): GeneratedCode =
  let spec = PluginSpec(
    name: name,
    description: &"Auto-generated {widgetType} widget",
    language: Nim,
    target: Shell,
    features: @[widgetType],
    dependencies: @["sigma_shell"]
  )
  
  result = gen.generatePlugin(spec)

# Export C-compatible API for Rust FFI
proc code_generator_create(): ptr CodeGenerator {.exportc.} =
  var gen = newCodeGenerator()
  return addr gen

proc code_generator_destroy(gen: ptr CodeGenerator) {.exportc.} =
  # Cleanup
  discard

