# ── Main generator ────────────────────────────────────────────────────────
proc generate_shard*(shard_name, author, output_dir: string, tpl: ShardTemplate) =
  let shard_dir = output_dir / fmt"sigma-shard-{shard_name}"
  let src_dir   = shard_dir / "src"
  createDir(src_dir)

  let files = [
    (shard_dir / "Cargo.toml",       gen_cargo_toml(shard_name, author)),
    (src_dir   / "lib.rs",           gen_lib_rs(shard_name, tpl)),
    (shard_dir / "sigma-shard.toml", gen_sigma_manifest(shard_name, tpl)),
    (shard_dir / ".github" / "workflows" / "ci.yml", gen_ci_yml(shard_name)),
    (shard_dir / "README.md",        gen_readme(shard_name, tpl)),
    (shard_dir / "WIKI_STUB.md",     gen_wiki_stub(shard_name)),
  ]
  for (path, content) in files:
    createDir(path.parentDir())
    writeFile(path, content)

  echo fmt"\e[38;2;52;211;153m✓ Shard scaffold generated: {shard_dir}\e[0m"
  echo fmt"\n  Structure:"
  echo fmt"  {shard_dir}/"
  echo fmt"  ├── Cargo.toml"
  echo fmt"  ├── sigma-shard.toml    (SDF manifest)"
  echo fmt"  ├── src/lib.rs          (probe/init/run/shutdown + tests)"
  echo fmt"  ├── README.md"
  echo fmt"  └── .github/workflows/ci.yml"
  echo fmt"\n  Next steps:"
  echo fmt"  1. cd {shard_dir} && cargo build --release"
  echo fmt"  2. Implement probe()/init()/run() in src/lib.rs"
  echo fmt"  3. sigma-pkg publish sigma-shard-{shard_name}"
  echo fmt"  4. Submit PR to github.com/AaryanSinghChauhan09/SigmaOS"

# ── CLI ────────────────────────────────────────────────────────────────────
proc shard_gen_cmd*(args: seq[string]) =
  if args.len == 0 or args[0] == "help":
    echo """sigma-shard-new — Shard skeleton generator

Usage:
  sigma-shard-new <name>                       Minimal shard
  sigma-shard-new <name> --template <tpl>      Template-based shard
  sigma-shard-new <name> --output <dir>        Custom output directory
  sigma-shard-new <name> --author "Name"       Set author
  sigma-shard-new --list                        List available templates

Templates:
  networking    Network device driver (sigma-bus: BUS_NETWORK)
  storage       Block storage driver (BUS_STORAGE)
  security      Security enforcer shard (BUS_SECURITY)
  audio         Audio device driver (BUS_AUDIO)
  display       Display/GPU driver (BUS_DISPLAY)
  input         Input device driver (BUS_INPUT)
  ipc           IPC relay shard (BUS_CUSTOM)
  cli           CLI tool shard (no bus)
  minimal       Bare-bones shard (default)

Examples:
  sigma-shard-new my-wifi-driver --template networking
  sigma-shard-new sigma-usb3 --template storage --author "Jane Dev"
  sigma-shard-new my-security-check --template security
  sigma-shard-new --list
"""
    return

  if args[0] == "--list":
    echo "Available templates:"
    for t in [TplNetworking, TplStorage, TplSecurity, TplAudio,
              TplDisplay, TplInput, TplIpc, TplCli, TplMinimal]:
      echo fmt"  {$t:<20} pledge={tpl_pledge(t)}"
    return

  let shard_name = args[0].toLowerAscii.replace(" ", "-")
  let tpl_idx    = args.find("--template")
  let tpl        = if tpl_idx >= 0 and tpl_idx+1 < args.len:
                     tpl_from_str(args[tpl_idx+1])
                   else: TplMinimal
  let out_idx    = args.find("--output")
  let out_dir    = if out_idx >= 0 and out_idx+1 < args.len: args[out_idx+1]
                   else: getCurrentDir()
  let auth_idx   = args.find("--author")
  let author     = if auth_idx >= 0 and auth_idx+1 < args.len: args[auth_idx+1]
                   else: "SigmaOS Contributor"

  generate_shard(shard_name, author, out_dir, tpl)
