import std/[os, strutils, strformat, osproc, json]

# ── Shard templates ───────────────────────────────────────────────────────
type ShardTemplate = enum
  TplNetworking, TplStorage, TplSecurity, TplAudio,
  TplDisplay, TplInput, TplIpc, TplMinimal, TplCli

proc tpl_from_str(s: string): ShardTemplate =
  case s.toLowerAscii
  of "networking","net":  TplNetworking
  of "storage","disk":    TplStorage
  of "security","sec":    TplSecurity
  of "audio","sound":     TplAudio
  of "display","gpu":     TplDisplay
  of "input","hid":       TplInput
  of "ipc","bus":         TplIpc
  of "cli","tool":        TplCli
  else:                   TplMinimal

proc tpl_pledge(t: ShardTemplate): string =
  case t
  of TplNetworking: "\"stdio\", \"rpath\", \"inet\""
  of TplStorage:    "\"stdio\", \"rpath\", \"wpath\", \"cpath\""
  of TplSecurity:   "\"stdio\""
  of TplAudio:      "\"stdio\", \"audio\""
  of TplDisplay:    "\"stdio\", \"video\""
  of TplInput:      "\"stdio\", \"device\""
  of TplIpc:        "\"stdio\""
  of TplCli:        "\"stdio\", \"rpath\""
  else:             "\"stdio\""

proc tpl_bus_channel(t: ShardTemplate): string =
  case t
  of TplNetworking: "BUS_NETWORK"
  of TplStorage:    "BUS_STORAGE"
  of TplSecurity:   "BUS_SECURITY"
  of TplAudio:      "BUS_AUDIO"
  of TplDisplay:    "BUS_DISPLAY"
  of TplInput:      "BUS_INPUT"
  of TplIpc:        "BUS_CUSTOM"
  else:             "BUS_SHARD"

