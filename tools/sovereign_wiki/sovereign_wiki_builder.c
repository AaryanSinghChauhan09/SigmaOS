// Replaces: scripts/wiki_builder.py, kernel/suites/S10_Registry/wiki_builder.py
// Competitor USPs Absorbed:
//   • Doxygen   — AST-scanning C doc extraction, no Python runtime
//   • Javadoc   — structured /// comment parsing
//   • Rustdoc   — inline module-level documentation from source
// Zero external deps — single-file, compiles with gcc -std=c11 -O2
// =============================================================================

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sigma_types.h>

#include <dirent.h>
#include <sys/stat.h>

#define MAX_PATH_LEN    1024
#define MAX_DOC_LINE    512
#define WIKI_VERSION    "2.0.0"

// ── Shard Doc Entry ───────────────────────────────────────────────────────────
typedef struct {
    char suite[32];
    char filename[128];
    char title[128];
    char usps[512];    // Extracted from "Competitor USPs Absorbed:" block
    char description[512];
} ShardDoc;

static ShardDoc docs[1024];
static uint32_t doc_count = 0;

// ── Extract doc metadata from a .c/.h source file ─────────────────────────────
static bool extract_shard_doc(const char* path, const char* suite,
                               const char* filename) {
    FILE* f = fopen(path, "r");
    if (!f) return false;

    ShardDoc* doc = &docs[doc_count];
    strncpy(doc->suite,    suite,    31);
    strncpy(doc->filename, filename, 127);
    doc->usps[0]        = '\0';
    doc->description[0] = '\0';
    doc->title[0]       = '\0';

    char line[MAX_DOC_LINE];
    bool in_usps = false;

    while (fgets(line, sizeof(line), f)) {
        // Grab shard title from // SigmaOS — Suite — ShardName
        if (strstr(line, "// SigmaOS —") && doc->title[0] == '\0') {
            char* dash = strstr(line, "—");
            if (dash) {
                dash = strstr(dash + 3, "—");
                if (dash) strncpy(doc->title, dash + 2, 127);
                // Strip trailing newline
                char* nl = strchr(doc->title, '\n');
                if (nl) *nl = '\0';
            }
        }
        // Grab USP block
        if (strstr(line, "Competitor USPs Absorbed:")) { in_usps = true; continue; }
        if (in_usps) {
            if (strstr(line, "//   •")) {
                strncat(doc->usps, line + 6,
                        sizeof(doc->usps) - strlen(doc->usps) - 1);
            } else if (strstr(line, "// Architecture") ||
                       strstr(line, "// Zero") ||
                       strstr(line, "#include")) {
                in_usps = false;
            }
        }
    }
    fclose(f);
    if (doc->title[0] == '\0')
        strncpy(doc->title, filename, 127);

    doc_count++;
    return true;
}

// ── Walk a suite directory ─────────────────────────────────────────────────────
static void walk_suite(const char* suite_path, const char* suite_name) {
    DIR* dir = opendir(suite_path);
    if (!dir) return;
    struct dirent* entry;
    while ((entry = readdir(dir)) != NULL) {
        if (entry->d_name[0] == '.') continue;
        const char* ext = strrchr(entry->d_name, '.');
        if (!ext) continue;
        if (strcmp(ext, ".c") != 0 && strcmp(ext, ".h") != 0 &&
            strcmp(ext, ".rs") != 0) continue;

        char full_path[MAX_PATH_LEN];
        snprintf(full_path, sizeof(full_path), "%s/%s", suite_path, entry->d_name);
        extract_shard_doc(full_path, suite_name, entry->d_name);
    }
    closedir(dir);
}

// ── Emit Markdown wiki page ───────────────────────────────────────────────────
static void emit_wiki_markdown(const char* out_path) {
    FILE* f = fopen(out_path, "w");
    if (!f) { fprintf(stderr, "Cannot open %s\n", out_path); return; }

    fprintf(f, "# SigmaOS Sovereign Shard Wiki\n");
    fprintf(f, "> Auto-generated by `sovereign_wiki_builder` v%s\n\n", WIKI_VERSION);
    fprintf(f, "| Suite | Shard | USPs Absorbed |\n");
    fprintf(f, "|:------|:------|:--------------|\n");

    for (uint32_t i = 0; i < doc_count; i++) {
        ShardDoc* d = &docs[i];
        // Collapse multi-line USP to single line
        char usps_flat[512];
        strncpy(usps_flat, d->usps, 511);
        for (char* c = usps_flat; *c; c++) if (*c == '\n') *c = ' ';

        fprintf(f, "| `%s` | `%s` | %s |\n",
                d->suite, d->filename, usps_flat[0] ? usps_flat : "—");
    }

    fprintf(f, "\n_Total shards documented: %u_\n", doc_count);
    fclose(f);
    printf("[sigma-wiki] Written %u entries → %s\n", doc_count, out_path);
}

int main(int argc, char* argv[]) {
    const char* suites_root = (argc > 1) ? argv[1] : "kernel/suites";
    const char* output_file = (argc > 2) ? argv[2] : "WIKI/AUTO_SOVEREIGN_WIKI.md";

    // Walk known suites
    const char* suites[] = {
        "S01_Genesis","S02_ZenithUI","S03_Orchestrator","S04_HAL",
        "S05_Memory","S06_Storage","S07_Network","S08_Security",
        "S09_Intelligence","S10_System","S10_Registry"
    };
    for (int i = 0; i < 11; i++) {
        char suite_path[MAX_PATH_LEN];
        snprintf(suite_path, sizeof(suite_path), "%s/%s", suites_root, suites[i]);
        walk_suite(suite_path, suites[i]);
    }
    emit_wiki_markdown(output_file);
    return 0;
}

