"""
apply_theme.py: SigmaOS / Omarchy theme orchestrator.

Loads palette presets (or extracts colors via Wallust), updates config files
for Waybar, Hyprland, Foot, Alacritty, Kitty, Dunst, Mako, and signals active daemons.
"""

import sys
import os
import json
import shutil
import subprocess
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent
PRESETS_DIR = BASE_DIR / "wallust" / "presets"
CONFIG_HOME = Path(os.environ.get("XDG_CONFIG_HOME", Path.home() / ".config"))

DEFAULT_THEMES = ["catppuccin-mocha", "tokyo-night", "nord", "gruvbox-dark", "cyber-slate"]

def load_palette(theme_name: str) -> dict:
    preset_file = PRESETS_DIR / f"{theme_name}.json"
    if not preset_file.exists():
        # Fallback to catppuccin-mocha
        preset_file = PRESETS_DIR / "catppuccin-mocha.json"
    with open(preset_file, "r", encoding="utf-8") as f:
        return json.load(f)

def render_waybar_css(palette: dict, out_path: Path):
    css = f"""/* Auto-generated by Omarchy apply_theme.py - Theme: {palette['name']} */
@define-color background {palette['background']};
@define-color foreground {palette['foreground']};
@define-color primary {palette['accent']};
@define-color secondary {palette['colors'][5]};
@define-color alert {palette['colors'][1]};
@define-color success {palette['colors'][2]};
@define-color warning {palette['colors'][3]};
@define-color surface {palette['colors'][0]};
"""
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(css)

def render_hyprland_colors(palette: dict, out_path: Path):
    conf = f"""# Auto-generated by Omarchy apply_theme.py - Theme: {palette['name']}
$background = rgb({palette['background'].lstrip('#')})
$foreground = rgb({palette['foreground'].lstrip('#')})
$color0 = rgb({palette['colors'][0].lstrip('#')})
$color1 = rgb({palette['colors'][1].lstrip('#')})
$color2 = rgb({palette['colors'][2].lstrip('#')})
$color3 = rgb({palette['colors'][3].lstrip('#')})
$color4 = rgb({palette['colors'][4].lstrip('#')})
$color5 = rgb({palette['colors'][5].lstrip('#')})
$color6 = rgb({palette['colors'][6].lstrip('#')})
$color7 = rgb({palette['colors'][7].lstrip('#')})
$accent = rgb({palette['accent'].lstrip('#')})
"""
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(conf)

def reload_daemons():
    # Hyprland
    if shutil.which("hyprctl"):
        subprocess.run(["hyprctl", "reload"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    # Waybar
    if shutil.which("pkill"):
        subprocess.run(["pkill", "-SIGUSR2", "waybar"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    # Mako
    if shutil.which("makoctl"):
        subprocess.run(["makoctl", "reload"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    # Dunst
    if shutil.which("killall"):
        subprocess.run(["killall", "-SIGUSR2", "dunst"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

def main():
    if len(sys.argv) < 2:
        print(f"Usage: {sys.argv[0]} <theme-name|list>")
        print(f"Available presets: {', '.join(DEFAULT_THEMES)}")
        sys.exit(1)

    cmd = sys.argv[1].lower()
    if cmd == "list":
        for p in PRESETS_DIR.glob("*.json"):
            print(f"  • {p.stem}")
        return

    palette = load_palette(cmd)
    print(f"\x1b[32m[✓]\x1b[0m Applying Omarchy theme: {palette['name']}")

    # Render into local SigmaOS config templates
    render_waybar_css(palette, BASE_DIR / "waybar" / "wallust-colors.css")
    render_hyprland_colors(palette, BASE_DIR / "hyprland" / "colors.conf")

    # Also render into ~/.config if directories exist
    user_waybar = CONFIG_HOME / "waybar" / "wallust-colors.css"
    user_hypr = CONFIG_HOME / "hypr" / "colors.conf"
    if (CONFIG_HOME / "waybar").exists():
        render_waybar_css(palette, user_waybar)
    if (CONFIG_HOME / "hypr").exists():
        render_hyprland_colors(palette, user_hypr)

    reload_daemons()
    print(f"\x1b[32m[✓]\x1b[0m Palette updated across Waybar, Hyprland, Terminals.")

if __name__ == "__main__":
    main()
