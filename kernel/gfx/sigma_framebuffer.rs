#[no_mangle]
pub unsafe extern "C" fn sigma_fb_init(base: u64, width: u32, height: u32, stride: u32, bpp: u32) -> i32 {
    if framebuffer_init(base, width, height, stride, bpp) { 0 } else { -1 }
}

#[no_mangle]
pub unsafe extern "C" fn sigma_fb_putpixel(x: u32, y: u32, r: u8, g: u8, b: u8, a: u8) {
    putpixel(x, y, Color::new(r, g, b, a));
}

