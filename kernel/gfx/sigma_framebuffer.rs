use core::sync::atomic::{AtomicBool, Ordering};

// ── Framebuffer info ─────────────────────────────────────────────────────

#[repr(C)]
#[derive(Copy, Clone, Debug)]
pub struct FramebufferInfo {
    pub base_addr:   u64,    // Physical address of framebuffer
    pub width:       u32,    // Width in pixels
    pub height:      u32,    // Height in pixels
    pub stride:      u32,    // Bytes per line
    pub bpp:         u32,    // Bits per pixel (32 for RGB888, 16 for RGB565)
    pub red_mask:    u32,
    pub green_mask:  u32,
    pub blue_mask:   u32,
    pub reserved_mask: u32,
}

impl FramebufferInfo {
    pub const fn new() -> Self {
        Self {
            base_addr: 0,
            width: 0,
            height: 0,
            stride: 0,
            bpp: 32,
            red_mask: 0xFF0000,
            green_mask: 0x00FF00,
            blue_mask: 0x0000FF,
            reserved_mask: 0xFF000000,
        }
    }

    pub fn size(&self) -> usize {
        (self.stride * self.height) as usize
    }

    pub fn is_valid(&self) -> bool {
        self.base_addr != 0 && self.width > 0 && self.height > 0
    }
}

// ── Global framebuffer state ─────────────────────────────────────────────

static mut G_FRAMEBUFFER: Option<FramebufferInfo> = None;
static mut G_FRAMEBUFFER_PTR: *mut u8 = core::ptr::null_mut();
static G_FRAMEBUFFER_INIT: AtomicBool = AtomicBool::new(false);

// ── Color structures ─────────────────────────────────────────────────────

#[derive(Copy, Clone, Debug)]
#[repr(C)]
pub struct Color {
    pub r: u8,
    pub g: u8,
    pub b: u8,
    pub a: u8,
}

impl Color {
    pub const fn new(r: u8, g: u8, b: u8, a: u8) -> Self {
        Self { r, g, b, a }
    }

    pub const fn rgb(r: u8, g: u8, b: u8) -> Self {
        Self::new(r, g, b, 255)
    }

    pub const fn to_u32(&self) -> u32 {
        ((self.a as u32) << 24) | ((self.b as u32) << 16) | ((self.g as u32) << 8) | (self.r as u32)
    }

    pub const BLACK: Color = Color::rgb(0, 0, 0);
    pub const WHITE: Color = Color::rgb(255, 255, 255);
    pub const RED: Color = Color::rgb(255, 0, 0);
    pub const GREEN: Color = Color::rgb(0, 255, 0);
    pub const BLUE: Color = Color::rgb(0, 0, 255);
    pub const YELLOW: Color = Color::rgb(255, 255, 0);
    pub const CYAN: Color = Color::rgb(0, 255, 255);
    pub const MAGENTA: Color = Color::rgb(255, 0, 255);
}

// ── Framebuffer operations ─────────────────────────────────────────────

/// Initialize framebuffer from UEFI GOP or VBE
pub unsafe fn framebuffer_init(base: u64, width: u32, height: u32, stride: u32, bpp: u32) -> bool {
    let info = FramebufferInfo {
        base_addr: base,
        width,
        height,
        stride,
        bpp,
        red_mask: if bpp == 32 { 0xFF0000 } else { 0xF800 },
        green_mask: if bpp == 32 { 0x00FF00 } else { 0x07E0 },
        blue_mask: if bpp == 32 { 0x0000FF } else { 0x001F },
        reserved_mask: if bpp == 32 { 0xFF000000 } else { 0 },
    };

    if !info.is_valid() {
        return false;
    }

    G_FRAMEBUFFER = Some(info);
    G_FRAMEBUFFER_PTR = base as *mut u8;
    G_FRAMEBUFFER_INIT.store(true, Ordering::Relaxed);
    true
}

pub fn is_initialized() -> bool {
    G_FRAMEBUFFER_INIT.load(Ordering::Relaxed)
}

pub unsafe fn get_info() -> Option<FramebufferInfo> {
    G_FRAMEBUFFER
}

/// Put a single pixel at (x, y)
pub unsafe fn putpixel(x: u32, y: u32, color: Color) {
    if !is_initialized() {
        return;
    }

    let info = match get_info() {
        Some(i) => i,
        None => return,
    };

    if x >= info.width || y >= info.height {
        return;
    }

    let offset = (y as usize * info.stride as usize) + (x as usize * (info.bpp / 8) as usize);
    let ptr = G_FRAMEBUFFER_PTR.add(offset);

    match info.bpp {
        32 => {
            let c = color.to_u32();
            *(ptr as *mut u32) = c;
        }
        16 => {
            // RGB565 conversion
            let r = (color.r as u32 >> 3) & 0x1F;
            let g = (color.g as u32 >> 2) & 0x3F;
            let b = (color.b as u32 >> 3) & 0x1F;
            let c = (r << 11) | (g << 5) | b;
            *(ptr as *mut u16) = c as u16;
        }
        _ => {}
    }
}

/// Get a single pixel at (x, y)
pub unsafe fn getpixel(x: u32, y: u32) -> Option<Color> {
    if !is_initialized() {
        return None;
    }

    let info = match get_info() {
        Some(i) => i,
        None => return None,
    };

    if x >= info.width || y >= info.height {
        return None;
    }

    let offset = (y as usize * info.stride as usize) + (x as usize * (info.bpp / 8) as usize);
    let ptr = G_FRAMEBUFFER_PTR.add(offset);

    match info.bpp {
        32 => {
            let c = *(ptr as *mut u32);
            Some(Color::new(
                (c & 0xFF) as u8,
                ((c >> 8) & 0xFF) as u8,
                ((c >> 16) & 0xFF) as u8,
                ((c >> 24) & 0xFF) as u8,
            ))
        }
        16 => {
            let c = *(ptr as *mut u16) as u32;
            let r = ((c >> 11) & 0x1F) << 3;
            let g = ((c >> 5) & 0x3F) << 2;
            let b = (c & 0x1F) << 3;
            Some(Color::new(r as u8, g as u8, b as u8, 255))
        }
        _ => None,
    }
}

/// Fill a rectangle with a solid color
pub unsafe fn fill_rect(x: u32, y: u32, w: u32, h: u32, color: Color) {
    if !is_initialized() {
        return;
    }

    let info = match get_info() {
        Some(i) => i,
        None => return,
    };

    let x_end = (x + w).min(info.width);
    let y_end = (y + h).min(info.height);

    for py in y..y_end {
        for px in x..x_end {
            putpixel(px, py, color);
        }
    }
}

/// Clear the entire framebuffer with a color
pub unsafe fn clear(color: Color) {
    if !is_initialized() {
        return;
    }

    let info = match get_info() {
        Some(i) => i,
        None => return,
    };

    fill_rect(0, 0, info.width, info.height, color);
}

/// Copy a rectangular region (blit)
pub unsafe fn blit(src_x: u32, src_y: u32, dst_x: u32, dst_y: u32, w: u32, h: u32) {
    if !is_initialized() {
        return;
    }

    let info = match get_info() {
        Some(i) => i,
        None => return,
    };

    let x_end = w.min(info.width - src_x.max(dst_x));
    let y_end = h.min(info.height - src_y.max(dst_y));

    for py in 0..y_end {
        for px in 0..x_end {
            if let Some(color) = getpixel(src_x + px, src_y + py) {
                putpixel(dst_x + px, dst_y + py, color);
            }
        }
    }
}

