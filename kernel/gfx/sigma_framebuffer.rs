/// Console state for text rendering
static mut CONSOLE_X: u32 = 0;
static mut CONSOLE_Y: u32 = 0;
const FONT_WIDTH: u32 = 8;
const FONT_HEIGHT: u32 = 8;

/// Draw a single character
pub unsafe fn putchar(c: char, x: u32, y: u32, fg: Color, bg: Color) {
    let idx = if c < ' ' || c > '~' { 0 } else { (c as usize) - 0x20 };
    let font_data = FONT_DATA[idx * 8..(idx + 1) * 8].as_ptr();

    for row in 0..8u32 {
        let byte = *font_data.add(row as usize);
        for col in 0..8u32 {
            let color = if (byte >> (7 - col)) & 1 == 1 { fg } else { bg };
            putpixel(x + col, y + row, color);
        }
    }
}

/// Print a string at current console position
pub unsafe fn puts(s: &str, fg: Color, bg: Color) {
    if !is_initialized() {
        return;
    }

    let info = match get_info() {
        Some(i) => i,
        None => return,
    };

    let cols = info.width / FONT_WIDTH;
    let rows = info.height / FONT_HEIGHT;

    for c in s.chars() {
        match c {
            '\n' => {
                CONSOLE_X = 0;
                CONSOLE_Y += 1;
                if CONSOLE_Y >= rows {
                    CONSOLE_Y = 0;
                }
            }
            '\r' => {
                CONSOLE_X = 0;
            }
            '\t' => {
                CONSOLE_X = (CONSOLE_X + 4) & !3;
                if CONSOLE_X >= cols {
                    CONSOLE_X = 0;
                    CONSOLE_Y += 1;
                }
            }
            _ => {
                putchar(c, CONSOLE_X * FONT_WIDTH, CONSOLE_Y * FONT_HEIGHT, fg, bg);
                CONSOLE_X += 1;
                if CONSOLE_X >= cols {
                    CONSOLE_X = 0;
                    CONSOLE_Y += 1;
                    if CONSOLE_Y >= rows {
                        CONSOLE_Y = 0;
                    }
                }
            }
        }
    }
}

/// Clear console and reset cursor
pub unsafe fn console_clear(bg: Color) {
    clear(bg);
    CONSOLE_X = 0;
    CONSOLE_Y = 0;
}

